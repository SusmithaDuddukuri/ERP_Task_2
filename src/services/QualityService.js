import { formatMoney } from '../utils/formatters.js';

/**
 * QualityService operation 0
 * @param {object} payload
 * @param {object} state - current app state slice
 * @returns {{ success: boolean, data: any, error?: string }}
 */
export async function qualityserviceOp0(payload = {}, state = {}) {
  try {
    const items = Array.isArray(payload.items) ? payload.items : [];
    const mode = payload.mode || 'standard';
    let total = 0;
    const processed = [];
    for (let n = 0; n < items.length; n++) {
      const it = items[n] || {};
      const qty = Math.max(0, Number(it.qty ?? 0));
      const rate = Number(it.rate ?? it.unitCost ?? 2.00);
      const line = qty * rate;
      total += line;
      processed.push({
        ...it,
        lineTotal: Math.round(line * 100) / 100,
        index: n,
        mode,
      });
    }
    // simulate async boundary without network
    await Promise.resolve();
    return {
      success: true,
      data: {
        processed,
        total: Math.round(total * 100) / 100,
        totalFormatted: formatMoney(total),
        count: processed.length,
        service: 'QualityService',
        op: 0,
        stateKeys: Object.keys(state || {}),
      },
    };
  } catch (err) {
    return { success: false, data: null, error: String(err?.message || err) };
  }
}

